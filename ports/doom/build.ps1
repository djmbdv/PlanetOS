<#
.SYNOPSIS
    Builds the DOOM port (doomgeneric) for PlanetOS.

.DESCRIPTION
    Translates the C sources in upstream/ with c2vala, applies the port fixes in
    fix_doom_vala.py, and compiles the result with planc against the SDK in the
    PlanetOS artifact directory.

    The generated Vala (doom_combined2.vala) is committed, so a plain build does
    not need c2vala; -Regenerate refreshes it.

.PARAMETER Regenerate
    Re-translate upstream/*.c and re-apply fix_doom_vala.py before compiling.

.PARAMETER Out
    Artifact directory with the built SDK (library/). Defaults to
    $env:PLANETOS_OUT, or <msys64>\tmp\planetos-qemu. Build it first with
    .\run-qemu.ps1 -BuildOnly.

.EXAMPLE
    .\run-qemu.ps1 -BuildOnly
    .\ports\doom\build.ps1
    .\run-qemu.ps1 -Headless -Add doom.elf,freedoom1.wad `
        -Run 'doom.elf -iwad /freedoom1.wad' -RunSeconds 60
#>
[CmdletBinding()]
param(
    [switch]$Regenerate,
    [string]$Out = ''
)

$ErrorActionPreference = 'Stop'

$Port = $PSScriptRoot
$Root = Split-Path -Parent (Split-Path -Parent $Port)
$Upstream = Join-Path $Port 'upstream'
$Combined = Join-Path $Port 'doom_combined2.vala'
$Glue = Join-Path $Port 'doom_platform.vala'
$Runtime = Join-Path $Root 'tools\c2vala_rt.vala'
$Planc = Join-Path $Root 'planc\build\planc.exe'
$C2Vala = Join-Path $Root 'tools\c2vala\build\c2vala.exe'

function Fail([string]$Text) {
    Write-Host ('build: ' + $Text) -ForegroundColor Red
    exit 1
}

if ($Out -eq '') { $Out = $env:PLANETOS_OUT }
if (-not $Out) { $Out = Join-Path $env:USERPROFILE 'msys64\tmp\planetos-qemu' }
if (-not (Test-Path (Join-Path $Out 'library'))) {
    Fail ('no SDK in ' + $Out + '; run .\run-qemu.ps1 -BuildOnly first (or set -Out)')
}
if (-not (Test-Path $Planc)) { Fail ('missing ' + $Planc + '; run .\planc\build.sh') }

if ($Regenerate) {
    if (-not (Test-Path $C2Vala)) {
        Fail ('missing ' + $C2Vala + '; run tools/c2vala/build_host.sh')
    }
    $exclude = @()
    foreach ($line in Get-Content (Join-Path $Port 'exclude.txt')) {
        $t = $line.Trim()
        if ($t -ne '' -and -not $t.StartsWith('#')) { $exclude += $t }
    }
    $cfiles = Get-ChildItem (Join-Path $Upstream '*.c') |
        Where-Object { $exclude -notcontains $_.Name } |
        Sort-Object Name | ForEach-Object { $_.FullName }
    Write-Host ('c2vala: translating ' + $cfiles.Count + ' C files...')
    & $C2Vala @cfiles -I $Upstream -D PLANETOS_NOSOUND -o $Combined
    # c2vala exits non-zero when it leaves functions as stubs, which is expected
    # here (31 of them, all unreachable paths), so success is "the file exists".
    if (-not (Test-Path $Combined)) { Fail 'c2vala failed to write doom_combined2.vala' }
    Write-Host 'fix_doom_vala.py: applying the port fixes...'
    & python (Join-Path $Port 'fix_doom_vala.py') $Combined
    if ($LASTEXITCODE -ne 0) { Fail 'fix_doom_vala.py failed' }
    $hdr = @"
// Generated by c2vala from upstream/*.c, then post-fixed by
// fix_doom_vala.py (see README.md). Regenerate with:
//     .\ports\doom\build.ps1 -Regenerate
// Hand-written glue lives in doom_platform.vala.
"@
    $body = [IO.File]::ReadAllText($Combined)
    [IO.File]::WriteAllText($Combined, $hdr + "`n" + $body, (New-Object System.Text.UTF8Encoding($false)))
}

Write-Host 'planc: compiling doom.elf...'
$elf = Join-Path $Out 'doom.elf'
# -O2 enables the register allocator and the bounds-check elimination; the port
# needs planc >= the fix that stops the -O2 backend from releasing returned arrays.
& $Planc -O2 --target=planetos ('--library-dir=' + (Join-Path $Out 'library')) `
    --import-lib=cairo --import-lib=gdk $Runtime $Combined $Glue -o $elf
if ($LASTEXITCODE -ne 0 -or -not (Test-Path $elf)) { Fail 'planc failed' }

Write-Host ''
Write-Host ('Built ' + $elf)
Write-Host 'Run it (needs freedoom1.wad, see README.md):'
Write-Host '  .\run-qemu.ps1 -Headless -Add doom.elf,freedoom1.wad -Run ''doom.elf -iwad /freedoom1.wad'' -RunSeconds 60'
