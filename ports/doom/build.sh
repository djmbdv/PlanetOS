#!/usr/bin/env bash
# Builds the DOOM port (doomgeneric) for PlanetOS. See build.ps1 for the long
# description; this is the Linux/macOS/MSYS2 counterpart.
#
#   ./run-qemu.sh --build-only
#   ./ports/doom/build.sh
#   ./run-qemu.sh --headless --add=doom.elf --add=freedoom1.wad \
#       --run='doom.elf -iwad /freedoom1.wad' --run-seconds=60
set -euo pipefail

PORT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$PORT/../.." && pwd)"
UPSTREAM="$PORT/upstream"
COMBINED="$PORT/doom_combined2.vala"
GLUE="$PORT/doom_platform.plan"
RUNTIME="$ROOT/tools/c2plan_rt.plan"
PLANC="$ROOT/planc/build/planc"
C2VALA="$ROOT/tools/c2plan/build/c2plan"

REGEN=0
OUT="${PLANETOS_OUT:-$HOME/msys64/tmp/planetos-qemu}"
while [ $# -gt 0 ]; do
    case "$1" in
        --regenerate) REGEN=1 ;;
        --out=*) OUT="${1#--out=}" ;;
        *) echo "build.sh: unknown option $1" >&2; exit 2 ;;
    esac
    shift
done

die() { echo "build: $1" >&2; exit 1; }

[ -x "$PLANC" ] || [ -x "$PLANC.exe" ] || die "missing $PLANC; run ./planc/build.sh"
[ -x "$PLANC" ] || PLANC="$PLANC.exe"
[ -d "$OUT/library" ] || die "no SDK in $OUT; run ./run-qemu.sh --build-only first (or pass --out=)"

if [ "$REGEN" -eq 1 ]; then
    [ -x "$C2VALA" ] || [ -x "$C2VALA.exe" ] || die "missing $C2VALA; run tools/c2vala/build_host.sh"
    [ -x "$C2VALA" ] || C2VALA="$C2VALA.exe"
    CFILES=()
    while IFS= read -r name; do
        case "$name" in ''|'#'*) continue ;; esac
        CFILES+=("$UPSTREAM/$name")
    done < <(echo; for f in "$UPSTREAM"/*.c; do
        base="$(basename "$f")"
        if ! grep -qxF "$base" <(grep -v '^#' "$PORT/exclude.txt" | grep -v '^$'); then
            echo "$base"
        fi
    done | sort)
    echo "c2vala: translating ${#CFILES[@]} C files..."
    # c2vala exits non-zero when it leaves functions as stubs, which is expected
    # here (31 of them, all unreachable paths), so success is "the file exists".
    "$C2VALA" "${CFILES[@]}" -I "$UPSTREAM" -D PLANETOS_NOSOUND -o "$COMBINED" || true
    [ -f "$COMBINED" ] || die "c2vala failed to write doom_combined2.vala"
    echo "fix_doom_vala.py: applying the port fixes..."
    python3 "$PORT/fix_doom_vala.py" "$COMBINED"
    python3 - "$COMBINED" <<'PY'
import io, sys
p = sys.argv[1]
hdr = ("// Generated by c2vala from upstream/*.c, then post-fixed by\n"
       "// fix_doom_vala.py (see README.md). Regenerate with:\n"
       "//     ./ports/doom/build.sh --regenerate\n"
       "// Hand-written glue lives in doom_platform.vala.\n")
body = io.open(p, encoding="utf-8").read()
io.open(p, "w", encoding="utf-8").write(hdr + "\n" + body)
PY
fi

echo "planc: compiling doom.elf..."
# -O2 enables the register allocator and the bounds-check elimination.
"$PLANC" -O2 --target=planetos "--library-dir=$OUT/library" \
    --import-lib=cairo --import-lib=gdk "$RUNTIME" "$COMBINED" "$GLUE" -o "$OUT/doom.elf"

echo
echo "Built $OUT/doom.elf"
echo "Run it (needs freedoom1.wad, see README.md):"
echo "  ./run-qemu.sh --headless --add=doom.elf --add=freedoom1.wad \\"
echo "      --run='doom.elf -iwad /freedoom1.wad' --run-seconds=60"
