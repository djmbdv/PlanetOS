#!/usr/bin/env python3
"""Pre-rasterizes assets/LiberationMono-Regular.ttf at 10x20 into kernel/console_font.vala."""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF_PATH = ROOT / "assets" / "LiberationMono-Regular.ttf"
OUT_PATH = ROOT / "kernel" / "console_font.vala"

W, H = 10, 20
FONT_SIZE = 16


def render_glyph(font: ImageFont.FreeTypeFont, ch: str) -> list[int]:
    img = Image.new("L", (W, H), 0)
    draw = ImageDraw.Draw(img)
    # LiberationMono at 16px has advance ~9.6px and ascender ~14px -> baseline at y=15
    draw.text((0, 15), ch, fill=255, font=font, anchor="ls")
    rows = []
    for y in range(H):
        mask = 0
        for x in range(W):
            if img.getpixel((x, y)) >= 112:
                mask |= 1 << (W - 1 - x)
        rows.append(mask)
    return rows


def main() -> None:
    font = ImageFont.truetype(str(TTF_PATH), FONT_SIZE)
    lines = [
        "// Auto-generated 10x20 bitmap font from assets/LiberationMono-Regular.ttf (ASCII 32..126).",
        "// Generated by tools/gen_console_font.py — do not edit by hand.",
        "",
        "namespace Planet.Kernel {",
        "    public class ConsoleFont : Object {",
        "        // Returns 5 packed 10-bit rows for quadrant q (0..3) of ASCII ch (32..126).",
        "        public static int pack (int ch, int q) {",
        "            if (ch < 32 || ch > 126)",
        "                ch = 63;",
        "            int idx = (ch - 32) * 4 + q;",
    ]
    for code in range(32, 127):
        rows = render_glyph(font, chr(code))
        for q in range(4):
            val = 0
            for r in range(5):
                val |= (rows[q * 5 + r] & 0x3FF) << (r * 10)
            idx = (code - 32) * 4 + q
            lines.append(f"            if (idx == {idx}) return 0x{val:013X};")
    lines.extend([
        "            return 0;",
        "        }",
        "    }",
        "}",
        "",
    ])
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUT_PATH} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
