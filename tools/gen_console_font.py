#!/usr/bin/env python3
"""Pre-rasterizes assets/LiberationMono-Regular.ttf at 10x20 (2-bit AA) into kernel/console_font.vala."""

from pathlib import Path
from PIL import Image, ImageChops, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF_PATH = ROOT / "assets" / "LiberationMono-Regular.ttf"
OUT_PATH = ROOT / "kernel" / "console_font.vala"

W, H = 10, 20
FONT_SIZE = 16


def render_glyph_2bit(font: ImageFont.FreeTypeFont, ch: str) -> list[int]:
    img = Image.new("L", (W, H), 0)
    draw = ImageDraw.Draw(img)
    draw.text((0, 15), ch, fill=255, font=font, anchor="ls")
    rows = []
    for y in range(H):
        packed = 0
        for x in range(W):
            v = img.getpixel((x, y))
            lvl = 0
            if v >= 186:
                lvl = 3
            elif v >= 116:
                lvl = 2
            elif v >= 48:
                lvl = 1
            packed |= lvl << ((W - 1 - x) * 2)
        rows.append(packed)
    return rows


def render_saturn_2bit() -> list[int]:
    scale = 8
    sw, sh = W * scale, H * scale
    cx, cy = 5.0 * scale, 10.5 * scale
    r = 2.6 * scale
    rx, ry = 4.6 * scale, 1.35 * scale
    ring_w = int(0.85 * scale)

    ring = Image.new("L", (sw, sh), 0)
    ImageDraw.Draw(ring).ellipse([cx - rx, cy - ry, cx + rx, cy + ry], outline=255, width=ring_w)
    ring = ring.rotate(28, center=(cx, cy), resample=Image.BICUBIC)

    img = Image.new("L", (sw, sh), 0)
    img.paste(ring, (0, 0))
    draw = ImageDraw.Draw(img)
    draw.ellipse([cx - r - 0.3 * scale, cy - r - 0.3 * scale, cx + r + 0.3 * scale, cy + r + 0.3 * scale], fill=0)
    draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=255)

    front = Image.new("L", (sw, sh), 0)
    ImageDraw.Draw(front).arc([cx - rx, cy - ry, cx + rx, cy + ry], start=10, end=170, fill=255, width=ring_w)
    front = front.rotate(28, center=(cx, cy), resample=Image.BICUBIC)
    img = ImageChops.lighter(img, front).resize((W, H), Image.LANCZOS)

    rows = []
    for y in range(H):
        packed = 0
        for x in range(W):
            v = img.getpixel((x, y))
            lvl = 3 if v >= 186 else (2 if v >= 116 else (1 if v >= 48 else 0))
            packed |= lvl << ((W - 1 - x) * 2)
        rows.append(packed)
    return rows


def main() -> None:
    font = ImageFont.truetype(str(TTF_PATH), FONT_SIZE)
    lines = [
        "// Auto-generated 10x20 2-bit anti-aliased font from assets/LiberationMono-Regular.ttf.",
        "// Codes 32..126 = ASCII, code 127 = bullet (CP437 0x07), code 128 = Saturn (0x01).",
        "// Generated by tools/gen_console_font.py — do not edit by hand.",
        "",
        "namespace Planet.Kernel {",
        "    public sealed class ConsoleFont : Object {",
        "        // Returns 3 packed 20-bit rows (10 px * 2-bit AA) for slice q (0..6).",
        "        public static int pack (int ch, int q) {",
        "            if (ch == 7)",
        "                ch = 127;",
        "            else if (ch == 1)",
        "                ch = 128;",
        "            else if (ch < 32 || ch > 126)",
        "                ch = 63;",
        "            int idx = (ch - 32) * 7 + q;",
    ]
    for code in range(32, 129):
        if code == 128:
            rows = render_saturn_2bit()
        else:
            ch = "\u2022" if code == 127 else chr(code)
            rows = render_glyph_2bit(font, ch)
        for q in range(7):
            val = 0
            for r in range(3):
                row_idx = q * 3 + r
                if row_idx < H:
                    val |= (rows[row_idx] & 0xFFFFF) << (r * 20)
            idx = (code - 32) * 7 + q
            lines.append(f"            if (idx == {idx}) return 0x{val:015X};")
    lines.extend([
        "            return 0;",
        "        }",
        "    }",
        "}",
        "",
    ])
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUT_PATH} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
